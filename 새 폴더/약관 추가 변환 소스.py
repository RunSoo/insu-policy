import re

def flatten_markdown_tables(text: str) -> str:
    """
    마크다운 표(| ... |) 구조를 RAG 검색 및 Dify 텍스트 분할에 최적화된 
    '헤더: 값' 형태의 평탄화 텍스트로 변환합니다.
    """
    lines = text.split('\n')
    new_lines = []
    in_table = False
    headers = []

    for line in lines:
        stripped = line.strip()
        
        # 표의 파이프(|) 행 감지
        if stripped.startswith('|') and stripped.endswith('|'):
            # 구분선 행 (| --- | --- |) 무시
            if re.match(r'^\|(?:\s*:?-+:?\s*\|)+$', stripped):
                continue
            
            cells = [cell.strip() for cell in stripped.split('|')[1:-1]]
            
            if not in_table:
                # 첫 번째 행을 헤더 키 값으로 등록
                headers = cells
                in_table = True
            else:
                # 데이터 행을 '헤더명: Cell값' 조합으로 평탄화
                row_items = []
                for idx, cell in enumerate(cells):
                    header_name = headers[idx] if idx < len(headers) and headers[idx] else f"열{idx+1}"
                    if cell:
                        row_items.append(f"{header_name}: {cell}")
                
                if row_items:
                    new_lines.append(" - " + " / ".join(row_items))
        else:
            if in_table:
                in_table = False
                headers = []
            new_lines.append(line)

    return '\n'.join(new_lines)


def process_markdown(input_filepath, output_filepath, toc_list=None):
    if toc_list is None:
        toc_list = []

    with open(input_filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # 1. 페이지 번호 및 출처 노이즈 태그 제거
    # (- 130 -, 130, Page 12, 형태 단독 줄 삭제)
    content = re.sub(r'\[source:\s*\d+\]', '', content)
    content = re.sub(r'^\s*(?:-\s*)?\d+(?:\s*-)?\s*$', '', content, flags=re.MULTILINE)
    content = re.sub(r'^\s*Page\s*\d+(?:\s*of\s*\d+)?\s*$', '', content, flags=re.MULTILINE | re.IGNORECASE)

    # 2. 문장 중간에 불필요하게 포함된 '# ' 기호 제거 (Dify 청크 찢어짐 방지)
    content = re.sub(r'(?<!\n)#+\s*', '', content)

    # 3. 마크다운 표 구조 평탄화 (Key: Value 서술형 전환)
    content = flatten_markdown_tables(content)

    # 4. toc_list 항목 중 '줄바꿈으로 혼자 단독으로 존재하는 행'에만 $$$$ 붙이기
    for item in toc_list:
        escaped_item = re.escape(item.strip()).replace(r'\ ', r'\s*')
        # ^\s*(항목)\s*$ : 앞뒤 공백 외에 다른 문자가 없는 단독 줄만 매칭
        pattern = re.compile(rf'^\s*({escaped_item})\s*$', flags=re.MULTILINE)
        content = pattern.sub(r'\n\n$$$$ \1', content, count=1)

    # 5. 연쇄 공백 줄 정돈 (최대 2줄 공백 유지)
    content = re.sub(r'\n{3,}', '\n\n', content)

    with open(output_filepath, 'w', encoding='utf-8') as f:
        f.write(content)

    print("변환 완료! 생성된 파일:", output_filepath)



